"""Write each screen module's PostgreSQL statements into its api.py.

For every module under app/modules whose api.py binds one TABLE through query_list/query_get/
query_save/query_delete, this writes LIST_SQL, GET_SQL, INSERT_SQL, UPDATE_SQL, DELETE_SQL and
REFERENCED_BY_SQL between the "PostgreSQL queries" markers, using the live table definitions
(columns, defaults) and the backend reference contracts. Run it again after a schema migration;
the query functions themselves are left as written. Use --check to report files that would change.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.core.database import DatabaseSettings, connect
from app.core.resources import CATALOG
from app.core.sql_store import EXTRAS, Metadata, _contract_fields

START = "# --- PostgreSQL queries for this screen"
END = "# --- end of generated SQL"
# Blocks written before the move from SQL Server are replaced too.
OLD_STARTS = ("# --- SQL Server queries for this screen",)

TEMPLATE_BLOCK = re.compile(
    r"# Active local data-access queries\. Replace these functions with parameterized\n"
    r"# SQL in this same file when SQL Server integration is explicitly resumed\.\n"
    r"def query_list\(data\):\n.*?\ndef query_delete\(data, code\):\n    del data\[\"records\"\]\[TABLE\]\[code\]\n",
    re.S,
)
GENERATED_BLOCK = re.compile(
    "(?:" + "|".join(re.escape(s) for s in (START, *OLD_STARTS)) + r").*?" + re.escape(END) + r"\n", re.S
)

FUNCTIONS = '''

def query_list(data):
    return sql.fetch_all(data, TABLE, LIST_SQL)


def query_get(data, code):
    record = sql.fetch_one(data, TABLE, GET_SQL, code)
    if record is None:
        raise HTTPException(404, "Record not found")
    return record


def query_save(data, record):
    return sql.save(data, TABLE, record, INSERT_SQL, UPDATE_SQL)


def query_delete(data, code):
    sql.delete(data, TABLE, DELETE_SQL, code)


def query_referenced_by(data, code):
    return sql.referenced_by(data, TABLE, REFERENCED_BY_SQL, code)
'''


def lines(items, indent, sep=","):
    return (sep + "\n" + " " * indent).join(items)


def statements(meta, defaults, table):
    t = meta.tables[table]
    cols = [c for c, col in t.columns.items() if c in t.visible and not col.identity]
    select = [f"t.{c}" for c in cols] + ["x.data AS extras"]
    base = (
        f"SELECT {lines(select, 7)}\n"
        f"FROM {table} AS t\n"
        f"LEFT JOIN {EXTRAS} AS x\n"
        f"  ON x.table_name = '{table}' AND x.record_code = t.code"
    )
    values = [f"COALESCE(%({c})s, {defaults[(table, c)]})" if (table, c) in defaults else f"%({c})s" for c in cols]
    updatable = [c for c in cols if c != "code"] or ["code"]
    refs = sorted(
        (other, f["name"])
        for other, spec in CATALOG.items()
        for f in spec["fields"]
        if f.get("reference") == table and other in meta.tables
    )
    out = {
        "LIST_SQL": base + "\nORDER BY t.code",
        "GET_SQL": base + "\nWHERE t.code = %(code)s",
        "INSERT_SQL": (
            f"INSERT INTO {table} (\n    {lines(cols, 4)}\n)\n"
            f"VALUES (\n    {lines(values, 4)}\n)"
        ),
        "UPDATE_SQL": (
            f"UPDATE {table}\nSET {lines([f'{c} = %({c})s' for c in updatable], 4)}\n"
            "WHERE code = %(code)s"
        ),
        "DELETE_SQL": f"DELETE FROM {table}\nWHERE code = %(code)s",
    }
    if refs:
        cases = [
            f"WHEN EXISTS (SELECT 1 FROM {other} WHERE {col} = %(code)s) THEN '{other}'"
            for other, col in refs
        ]
        out["REFERENCED_BY_SQL"] = f"SELECT CASE\n    {lines(cases, 4, sep='')}\nEND AS referenced_by"
    else:
        out["REFERENCED_BY_SQL"] = None
    return out


def block(meta, defaults, table):
    parts = [
        f"{START} (generated by tools/generate_module_sql.py from the",
        "# live table definitions; regenerate after schema migrations). Values are bound as %(name)s",
        "# parameters, never formatted into the text; app.core.sql_queries runs these statements and",
        "# keeps custom fields (record_extras) with each record. Table names resolve through the",
        "# connection's search_path (EDUNEXA_DB_SCHEMA).",
    ]
    for name, sql in statements(meta, defaults, table).items():
        parts.append("")
        parts.append(f"{name} = None" if sql is None else f'{name} = """\n{sql}\n"""')
    parts.append(END)
    return "\n".join(parts) + "\n"


def rewrite(source, meta, defaults, table):
    generated = block(meta, defaults, table)
    if GENERATED_BLOCK.search(source):
        return GENERATED_BLOCK.sub(lambda _: generated, source, count=1).replace(
            "endpoints and their SQL Server queries.", "endpoints and their PostgreSQL queries.", 1
        )
    if not TEMPLATE_BLOCK.search(source):
        return None
    source = TEMPLATE_BLOCK.sub(lambda _: generated + FUNCTIONS, source, count=1)
    source = source.replace(
        "from app.core.resources import staff_only\n",
        "from app.core import sql_queries as sql\nfrom app.core.resources import staff_only\n",
        1,
    )
    source = source.replace(
        "    delete = staticmethod(query_delete)\n",
        "    delete = staticmethod(query_delete)\n    referenced_by = staticmethod(query_referenced_by)\n",
        1,
    )
    return source.replace(
        "endpoints and their queries. SQL connectivity is intentionally deferred.",
        "endpoints and their PostgreSQL queries.",
        1,
    ).replace("endpoints and their SQL Server queries.", "endpoints and their PostgreSQL queries.", 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="list files that would change")
    args = parser.parse_args()
    settings = DatabaseSettings()
    conn = connect(settings)
    try:
        cur = conn.cursor()
        meta = Metadata(cur, settings.db_schema, _contract_fields())
        cur.execute(
            "SELECT c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid) FROM pg_attrdef d"
            " JOIN pg_class c ON c.oid = d.adrelid"
            " JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum"
            " WHERE c.relnamespace = %s::regnamespace AND c.relkind = 'r'",
            (settings.db_schema,),
        )
        defaults = {(t, c): d for t, c, d in cur.fetchall()}
    finally:
        conn.close()

    changed, skipped = [], []
    for path in sorted((ROOT / "app" / "modules").rglob("api.py")):
        source = path.read_text()
        m = re.search(r'^TABLE = "(\w+)"', source, re.M)
        if not m or m.group(1) not in meta.tables:
            continue
        result = rewrite(source, meta, defaults, m.group(1))
        if result is None:
            skipped.append(path)
        elif result != source:
            changed.append(path)
            if not args.check:
                path.write_text(result)
    verb = "would change" if args.check else "updated"
    print(f"{len(changed)} module files {verb}; {len(skipped)} with TABLE but custom queries left alone")


if __name__ == "__main__":
    main()
