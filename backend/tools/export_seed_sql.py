"""Write the college's reference data as INSERT statements into both schema files.

Reads the institution, campuses, departments and courses (programs) from the configured
database and replaces the "seed data" block at the end of ../database/edunexa_schema_postgresql.sql
and ../database/edunexa_schema_mysql.sql, so a fresh install has the same course catalog.
Re-running it refreshes the block (for example after courses are edited in the dashboard).
Inserts skip rows whose code already exists (ON CONFLICT DO NOTHING / INSERT IGNORE).

    python tools/export_seed_sql.py
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.database import DATABASE_DIR, connect

START = "-- BEGIN EDUNEXA SEED DATA"
END = "-- END EDUNEXA SEED DATA"
TABLES = [
    ("institutions", ["code", "name", "email", "phone", "address", "city", "state", "postal_code", "country",
                      "website", "affiliation"]),
    ("campuses", ["code", "institution_code", "name", "address", "city", "state", "postal_code", "phone"]),
    ("departments", ["code", "campus_code", "name"]),
    ("programs", ["code", "department_code", "name", "qualification", "course_level", "branch", "category",
                  "duration_label", "semesters_label", "duration_semesters", "intake_capacity", "subjects",
                  "career_opportunities"]),
]


def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def read(cur):
    out = {}
    for table, wanted in TABLES:
        cur.execute("SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema()"
                    " AND table_name = %s", (table,))
        present = {r[0] for r in cur.fetchall()}
        columns = [c for c in wanted if c in present]
        cur.execute(f"SELECT {', '.join(columns)} FROM {table} ORDER BY "
                    + ("course_level DESC NULLS LAST, category, name" if table == "programs" else "code"))
        out[table] = (columns, cur.fetchall())
    return out


def block(data, dialect):
    lines = [START, "-- Reference data of the college: institution, campus, departments (one per course family)",
             "-- and the course catalog (Intermediate groups and degree courses). Generated by",
             "-- backend/tools/export_seed_sql.py from the live database; existing codes are skipped."]
    for table, (columns, rows) in data.items():
        if not rows:
            continue
        lines.append("")
        lines.append(f"-- {table}: {len(rows)}")
        head = ("INSERT IGNORE INTO" if dialect == "mysql" else "INSERT INTO") + f" {table} ({', '.join(columns)}) VALUES"
        values = [f"  ({', '.join(literal(v) for v in row)})" for row in rows]
        tail = ";" if dialect == "mysql" else "\nON CONFLICT (code) DO NOTHING;"
        lines.append(head + "\n" + ",\n".join(values) + tail)
    lines.append(END)
    return "\n".join(lines) + "\n"


def place(path, text, before_commit):
    source = path.read_text()
    source = re.sub(rf"\n?{re.escape(START)}.*?{re.escape(END)}\n", "\n", source, flags=re.S)
    if before_commit:
        body = source.rstrip()
        assert body.endswith("COMMIT;"), path
        source = body[: -len("COMMIT;")].rstrip() + "\n\n" + text + "\nCOMMIT;\n"
    else:
        source = source.rstrip() + "\n\n" + text
    path.write_text(source)


def main():
    conn = connect()
    try:
        data = read(conn.cursor())
    finally:
        conn.close()
    place(DATABASE_DIR / "edunexa_schema_postgresql.sql", block(data, "postgresql"), before_commit=True)
    place(DATABASE_DIR / "edunexa_schema_mysql.sql", block(data, "mysql"), before_commit=False)
    print(", ".join(f"{t}: {len(rows)}" for t, (_, rows) in data.items()), "written to both schema files")


if __name__ == "__main__":
    main()
